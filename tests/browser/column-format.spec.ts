	await page.mouse.down();
	await page.mouse.move(target!.x + target!.width / 2, target!.y + target!.height / 2 - 3, { steps: 10 });
	await page.mouse.up();
	await expect(page.getByRole('textbox', { name: 'Option 2', exact: true })).toHaveValue('=Ready');
	// Keyboard dragging uses the same handles; Escape cancels without closing the dialog.
	await page.getByRole('button', { name: 'Reorder option 2', exact: true }).focus();
	await page.keyboard.press('Space', { delay: 60 });
	await page.keyboard.press('ArrowUp', { delay: 60 });
