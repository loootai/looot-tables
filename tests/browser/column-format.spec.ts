// Exercise the actual UI and persistence requests without depending on a live Neon database.
test('column-wide formats display currency and units and persist checkbox booleans', async ({ page, context, baseURL }) => {
	await context.addCookies([{ name: 'enrichable.session', value: memberCookie('format-test'), url: baseURL!, httpOnly: true, sameSite: 'Lax' }]);
	const columns: Sheet['columns'] = ['Cost', 'Selected', 'Weight'].map((name, i) => ({ id: `c${i}`, name, type: 'source', width: 180, createdAt: 1 }));
	let sheet: Sheet = { id: 'format-test', name: 'Formats', columns, filters: [], sort: null, createdAt: 1, updatedAt: 1, revision: 1 };
	let rows: Row[] = [0, 1].map((i) => ({ id: `r${i}`, sheetId: sheet.id, order: i, createdAt: 1, cells: Object.fromEntries(columns.map((column, c) => [column.id, { v: c === 0 ? 1234.5 + i : c === 1 ? 'false' : 12.5 + i, s: 'done', t: 1 }])) }));
	await page.route('**/api/looot/balance*', (route) => route.fulfill({ json: { available: 5, reserved: 0 } }));
	await page.route('**/api/keys/verify*', (route) => route.fulfill({ json: { openai: false, looot: false, typesafe: false, passwordRequired: false } }));
	await page.route('**/api/sheets**', async (route) => {
		const request = route.request();
		if (request.method() === 'PATCH') {
			const body = request.postDataJSON();
			sheet = { ...body.sheet, revision: sheet.revision! + 1 };
			const updates = new Map<string, Row>(body.rows.map((row: Row) => [row.id, row]));
			rows = rows.map((row) => updates.get(row.id) ?? row);
			await route.fulfill({ json: { revision: sheet.revision, updatedAt: Date.now() } });
		} else if (new URL(request.url()).pathname === '/api/sheets') await route.fulfill({ json: [{ sheet, rowCount: rows.length }] });
		else await route.fulfill({ json: { sheet, rows, next: null } });
	});
	await page.goto(`/app/sheets/${sheet.id}`);
	await page.getByRole('dialog').waitFor();
	await page.getByRole('button', { name: 'Close', exact: true }).click();
	await expect(page.locator('[role="gridcell"]:not([aria-label^="New column"])').first()).toHaveText('1,234.5');
	async function openFormat(name: string) {
		await page.getByRole('button', { name: `Column menu for ${name}`, exact: true }).click();
		await page.getByRole('menuitem', { name: 'Field format', exact: true }).click();
	}
	async function saveFormat() { await page.getByRole('button', { name: 'Save format', exact: true }).click(); await expect(page.getByRole('dialog')).toHaveCount(0); }
	await openFormat('Cost');
	await page.getByRole('combobox', { name: 'Format', exact: true }).click();
	await page.getByRole('option', { name: 'Currency', exact: true }).click();
	await saveFormat();
	await expect(page.locator('[role="gridcell"]:not([aria-label^="New column"])').nth(0)).toHaveText('$1,234.50');
	await expect(page.locator('[role="gridcell"]:not([aria-label^="New column"])').nth(3)).toHaveText('$1,235.50');
	expect(rows[0].cells.c0.v).toBe(1234.5);
	await openFormat('Selected');
	await page.getByRole('combobox', { name: 'Format', exact: true }).click();
	await expect(page.getByRole('option', { name: /yes.*no/i })).toHaveCount(0);
	await page.getByRole('option', { name: 'Checkbox', exact: true }).click();
	await saveFormat();
	const boxes = page.getByRole('checkbox', { name: 'Selected checkbox', exact: true });
	await expect(boxes).toHaveCount(2);
	await expect(boxes.first()).not.toBeChecked();
	await boxes.first().check();
	await expect.poll(() => rows[0].cells.c1.v).toBe(true);
	expect(rows[1].cells.c1.v).toBe(false);
	await page.getByRole('button', { name: 'Undo', exact: true }).click();
	await expect(boxes.first()).not.toBeChecked();
	// The padding beside the visible checkbox is also clickable.
	const checkboxTarget = boxes.first().locator('..');
	const targetBounds = (await checkboxTarget.boundingBox())!;
	expect(targetBounds.width).toBe(36);
	expect(targetBounds.height).toBe(36);
	await checkboxTarget.click({ position: { x: 32, y: 18 } });
	await expect.poll(() => rows[0].cells.c1.v).toBe(true);
	await checkboxTarget.click({ position: { x: 4, y: 18 } });
	await expect.poll(() => rows[0].cells.c1.v).toBe(false);
	await boxes.first().check();
	await expect.poll(() => rows[0].cells.c1.v).toBe(true);
	await openFormat('Weight');
	await page.getByRole('combobox', { name: 'Format', exact: true }).click();
	await page.getByRole('option', { name: 'Number with unit', exact: true }).click();
	await page.getByLabel('Unit', { exact: true }).fill('kg');
	await saveFormat();
	await expect(page.locator('[role="gridcell"]:not([aria-label^="New column"])').nth(2)).toHaveText('12.5 kg');
	await page.reload();
	await expect(page.locator('[role="gridcell"]:not([aria-label^="New column"])').first()).toHaveText('$1,234.50');
	await expect(boxes.first()).toBeChecked();
	await expect(page.locator('[role="gridcell"]:not([aria-label^="New column"])').nth(5)).toHaveText('13.5 kg');
	expect(await page.pageErrors()).toEqual([]);
});

