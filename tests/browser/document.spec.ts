import { test, expect } from '@playwright/test';
import { memberCookie } from './authenticated-test';
import type { Sheet, Row } from '../../src/lib/types';
import { readFile } from 'node:fs/promises';

test('document chips open a Markdown preview, edit, and download a client PDF', async ({ page, context, baseURL }) => {
 await context.addCookies([{ name: 'enrichable.session', value: memberCookie('document-test'), url: baseURL!, httpOnly: true, sameSite: 'Lax' }]);
 const initial = '# Acme brief\n\n## Overview\n\nAcme builds **rockets**.\n\n- Founded in 2020\n- Based in Paris\n\n[Website](https://example.com)';
 let sheet: Sheet = { id: 'document-test', name: 'Documents', columns: [{ id: 'draft', name: 'Company brief', type: 'source', format: 'document', width: 240, createdAt: 1 }], filters: [], sort: null, createdAt: 1, updatedAt: 1, revision: 1 };
 let rows: Row[] = [{ id: 'r', sheetId: sheet.id, order: 0, createdAt: 1, cells: { draft: { v: initial, s: 'done', t: 1 } } }];
 await page.route('**/api/organization-settings', (route) => route.fulfill({ json: { local: true } }));
 await page.route('**/api/looot/balance*', (route) => route.fulfill({ json: { available: 5, reserved: 0 } }));
 await page.route('**/api/keys/verify*', (route) => route.fulfill({ json: { openai: false, context: false, typesafe: false, passwordRequired: false } }));
 const wordmark = (name: string) => 'data:image/svg+xml;base64,' + Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="400" height="160"><text x="80" y="90" font-family="sans-serif" font-size="22">${name}</text></svg>`).toString('base64');
 const logo = wordmark('Publisher');
 await page.route('**/api/documents/branding', async (route) => {
  const body = route.request().postDataJSON();
  if (!body.primaryDomain) return route.fulfill({ json: {} });
  expect(body.primaryDomain).toBe('publisher.com');
  if (body.secondaryDomain) expect(body.secondaryDomain).toBe('client.com');
  await route.fulfill({ json: { primary: { name: 'Publisher', domain: 'publisher.com', accentColor: '#c72555', logoUrl: logo }, secondary: body.secondaryDomain ? { name: 'Client', domain: 'client.com', logoUrl: wordmark('Client') } : undefined } });
 });
 await page.route('**/api/sheets**', async (route) => {
  const request = route.request();
  if (request.method() === 'PATCH') {
   const body = request.postDataJSON(); sheet = { ...body.sheet, revision: sheet.revision! + 1 };
   const updates = new Map<string, Row>(body.rows.map((row: Row) => [row.id, row])); rows = rows.map((row) => updates.get(row.id) ?? row);
   await route.fulfill({ json: { revision: sheet.revision, updatedAt: Date.now() } });
  } else if (new URL(request.url()).pathname === '/api/sheets') await route.fulfill({ json: [{ sheet, rowCount: rows.length }] });
  else await route.fulfill({ json: { sheet, rows, next: null } });
 });
 await page.goto(`/app/sheets/${sheet.id}`);
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button', { name: 'Close', exact: true }).click();
 await page.getByRole('link', { name: 'Configuration', exact: true }).click();
 const brandingSettings = page.getByRole('region', { name: 'Defaults' });
 await brandingSettings.getByLabel('Company website', { exact: true }).fill('publisher.com');
 await brandingSettings.getByRole('button', { name: 'Save defaults' }).click();
 await expect(brandingSettings.getByText('#c72555', { exact: true })).toBeVisible();
 await expect(brandingSettings.getByRole('button', { name: 'Save defaults' })).toBeDisabled();
 await page.reload();
 await expect(page.getByRole('region', { name: 'Defaults' }).getByLabel('Company website', { exact: true })).toHaveValue('publisher.com');
 // Setup opens at most once per browser, so neither the reload nor the sheet reopens it.
 await page.goto(`/app/sheets/${sheet.id}`);
 const cell = page.getByRole('gridcell').first();
 await expect(cell).toHaveText('Acme brief');
 await cell.locator("[data-document-chip]").click();
 const panel = page.getByRole('complementary', { name: 'Cell details' });
 await expect(panel.getByRole('heading', { name: 'Acme brief' })).toBeVisible();
 await expect(panel.locator('strong')).toHaveText('rockets');
 await panel.getByText('PDF branding', { exact: true }).click();
 await expect(panel.getByLabel('Your company website')).toHaveValue('publisher.com');
 await panel.getByLabel('Client website', { exact: true }).fill('client.com');
 const downloadEvent = page.waitForEvent('download');
 await panel.getByRole('button', { name: 'Download PDF' }).click();
 const download = await downloadEvent;
 expect(download.suggestedFilename()).toBe('Publisher × Client.pdf');
 await download.saveAs(test.info().outputPath('brief.pdf'));
 await panel.screenshot({ path: test.info().outputPath('document-preview.png') });
 const file = await download.path();
 const pdfBytes = await readFile(file!);
 expect(pdfBytes.subarray(0, 5).toString()).toBe('%PDF-');
 expect(pdfBytes.toString('latin1')).toContain('/Subtype /Image');
 await panel.getByRole('button', { name: 'Edit', exact: true }).click();
 await panel.getByLabel('Document Markdown').fill('temporary');
 await panel.getByLabel('Document Markdown').press('Meta+A');
 await panel.getByRole('button', { name: 'Add bold text (ctrl + b)', exact: true }).click();
 await expect(panel.getByLabel('Document Markdown')).toHaveValue('**temporary**');
 await panel.getByRole('button', { name: 'Cancel', exact: true }).click();
 await expect(panel.getByRole('heading', { name: 'Acme brief' })).toBeVisible();
 await expect(cell).toHaveText('Acme brief');
 await panel.getByRole('button', { name: 'Edit', exact: true }).click();
 await panel.getByLabel('Document Markdown').fill('# Updated brief\n\nUpdated research.');
 await panel.screenshot({ path: test.info().outputPath('document-editor.png') });
 await panel.getByRole('button', { name: 'Preview', exact: true }).click();
 await expect(panel.getByRole('heading', { name: 'Updated brief' })).toBeVisible();
 await expect(cell).toHaveText('Acme brief');
 await panel.getByRole('button', { name: 'Save', exact: true }).click();
 await expect(cell).toHaveText('Updated brief');
 await expect(panel.getByRole('heading', { name: 'Updated brief' })).toBeVisible();
 await expect.poll(() => rows[0].cells.draft.v).toBe('# Updated brief\n\nUpdated research.');
 await page.reload();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button', { name: 'Close', exact: true }).click();
 await expect(cell).toHaveText('Updated brief');
 expect(await page.pageErrors()).toEqual([]);
});
