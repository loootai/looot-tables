import { test, expect } from '@playwright/test';
import { memberCookie } from './authenticated-test';
import type { Sheet, Row } from '../../src/lib/types';

test('email drafts show collapsed recipients and persist field edits', async ({ page, context, baseURL }) => {
 await context.addCookies([{ name: 'enrichable.session', value: memberCookie('email-test'), url: baseURL!, httpOnly: true, sameSite: 'Lax' }]);
 const initial = { to: 'alice@example.com', cc: 'team@example.com', bcc: 'private@example.com', subject: 'Hello Alice', body: 'Hi Alice,\nLet’s talk.' };
 let sheet: Sheet = { id: 'email-test', name: 'Emails', columns: [{ id: 'draft', name: 'Email draft', type: 'source', format: 'email-draft', width: 240, createdAt: 1 }], filters: [], sort: null, createdAt: 1, updatedAt: 1, revision: 1 };
 let rows: Row[] = [{ id: 'r', sheetId: sheet.id, order: 0, createdAt: 1, cells: { draft: { v: JSON.stringify(initial), s: 'done', t: 1 } } }];
 await page.route('**/api/looot/balance*', (route) => route.fulfill({ json: { available: 5, reserved: 0 } }));
 await page.route('**/api/keys/verify*', (route) => route.fulfill({ json: { openai: false, looot: false, typesafe: false, passwordRequired: false } }));
 await page.route('**/api/sheets**', async (route) => {
  const request = route.request();
  if (request.method() === 'PATCH') {
   const body = request.postDataJSON(); sheet = { ...body.sheet, revision: sheet.revision! + 1 };
   const updates = new Map<string, Row>(body.rows.map((row: Row) => [row.id, row])); rows = rows.map((row) => updates.get(row.id) ?? row);
   await route.fulfill({ json: { revision: sheet.revision, updatedAt: Date.now() } });
  } else if (new URL(request.url()).pathname === '/api/sheets') await route.fulfill({ json: [{ sheet, rowCount: rows.length }] });
  else await route.fulfill({ json: { sheet, rows, next: null } });
 });
 await page.goto(`/app/sheets/${sheet.id}`);
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button', { name: 'Close', exact: true }).click();
 const cell = page.getByRole('gridcell').first();
 await expect(cell).toHaveText('Hello Alice'); await cell.dblclick();
 const panel = page.getByRole('complementary', { name: 'Cell details' });
 const create = panel.getByRole('link', { name: 'Create draft', exact: true });
 const picker = panel.getByRole('button', { name: 'Email app: Gmail', exact: true });
 await expect(create).toHaveAttribute('href', /^https:\/\/mail\.google\.com\//);
 await expect(create.locator('img')).toHaveAttribute('src', '/providers/email/gmail.svg');
 const [actionBox, pickerBox] = await Promise.all([create.boundingBox(), picker.boundingBox()]);
 expect(pickerBox!.x).toBeGreaterThan(actionBox!.x + actionBox!.width);
 expect(pickerBox!.y).toBe(actionBox!.y);
 await expect(panel.getByRole('button', { name: 'Edit draft', exact: true })).toHaveCount(0);
 await picker.click();
 await page.getByRole('menuitem', { name: 'Outlook', exact: true }).click();
 await expect(create).toHaveAttribute('href', /^https:\/\/outlook\.live\.com\//);
 await panel.getByRole('button', { name: 'Email app: Outlook', exact: true }).click();
 await page.getByRole('menuitem', { name: 'Gmail', exact: true }).click();
 await expect(create).toHaveAttribute('href', /^https:\/\/mail\.google\.com\//);
 await expect(panel.getByLabel('To', { exact: true })).toHaveValue(initial.to);
 await expect(panel.getByLabel('Body', { exact: true })).toHaveValue(initial.body);
 await expect(panel.getByLabel('Cc', { exact: true })).not.toBeVisible();
 await panel.getByText('Cc / Bcc', { exact: false }).click();
 await expect(panel.getByLabel('Bcc', { exact: true })).toHaveValue(initial.bcc);
 await panel.getByLabel('Subject', { exact: true }).fill('Updated subject');
 await panel.getByLabel('Body', { exact: true }).focus();
 await expect(cell).toHaveText('Updated subject');
 await expect.poll(() => JSON.parse(String(rows[0].cells.draft.v)).subject).toBe('Updated subject');
 expect(JSON.parse(String(rows[0].cells.draft.v)).bcc).toBe(initial.bcc);
 await panel.getByLabel('Body', { exact: true }).fill('Updated body');
 await expect(create).toHaveAttribute('href', /body=Updated%20body/);
 await panel.getByRole('button', { name: 'Close', exact: true }).click();
 await expect.poll(() => JSON.parse(String(rows[0].cells.draft.v)).body).toBe('Updated body');
 await page.reload();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button', { name: 'Close', exact: true }).click();
 await cell.dblclick();
 await expect(panel.getByLabel('Subject', { exact: true })).toHaveValue('Updated subject');
 await expect(panel.getByLabel('Body', { exact: true })).toHaveValue('Updated body');
 await expect(panel.getByLabel('Cc', { exact: true })).not.toBeVisible();
 expect(await page.pageErrors()).toEqual([]);
});
