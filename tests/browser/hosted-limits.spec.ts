import { test, expect } from '@playwright/test';
import { memberCookie } from './authenticated-test';

test('hosted limits keep Context.dev visible as a static meter and reveal trial balances on demand', async ({ page, context, baseURL }) => {
	await context.addCookies([{ name: 'enrichable.session', value: memberCookie('browser-user'), url: baseURL!, httpOnly: true, sameSite: 'Lax' }]);
	await page.route('**/api/organization-settings', route => route.fulfill({ json: { local: true } }));
	await page.route('**/api/keys/verify*', route => route.fulfill({ json: { openai: true, openaiTrial: { model: 'gpt-6-luna' }, enrichmentTrial: true, context: true, contextConnected: true } }));
	await page.route('**/api/sheets', route => route.fulfill({ json: [] }));
	await page.route('**/api/context/usage', route => route.fulfill({ json: { credits: 7200, used: 2800 } }));
	let remainingUsd = 0.58;
	await page.route('**/api/openai/usage', route => route.fulfill({ json: { enabled: true, grantedUsd: 1, remainingUsd, deploymentAvailable: true } }));
	await page.route('**/api/enrichment/usage', route => route.fulfill({ json: { enabled: true, grantedUsd: 1, remainingUsd: 0.85, deploymentAvailable: true } }));
	await page.goto('/app');
	const navigation = page.locator('#app-navigation');
	const toggle = page.getByRole('button', { name: 'Included trials', exact: true });
	const ai = page.getByRole('progressbar', { name: 'AI trial remaining' });
	const email = page.getByRole('progressbar', { name: 'Email credit remaining' });
	await expect(navigation).toContainText('7,200 credits left');
	await expect(navigation.getByRole('button', { name: /Context.dev/ }), 'The meter is a static display').toHaveCount(0);
	await expect(navigation.getByRole('link', { name: 'Manage', exact: true })).toHaveAttribute('href', '/app/settings');
	await expect(navigation.getByRole('link', { name: 'Top up', exact: true })).toHaveCount(0);
	await expect(page.getByRole('progressbar', { name: 'Context.dev credits remaining' })).toHaveAttribute('aria-valuenow', '72');
	await expect(toggle).toHaveAttribute('aria-expanded', 'false');
	await expect(ai).toBeHidden();
	await expect(email).toBeHidden();
	await toggle.focus();
	await page.keyboard.press('Enter');
	await expect(toggle).toHaveAttribute('aria-expanded', 'true');
	await expect(ai).toHaveAttribute('aria-valuenow', '58');
	await expect(email).toHaveAttribute('aria-valuenow', '85');
	await expect(navigation).toContainText('$0.58 of $1.00 left');
	await expect(navigation).toContainText('$0.85 of $1.00 left');
	await expect(page.getByRole('dialog')).toHaveCount(0);
	await toggle.click();
	await expect(ai).toBeHidden();
	remainingUsd = 0.42;
	await page.evaluate(() => window.dispatchEvent(new Event('focus')));
	await expect(page.locator('[aria-label="AI trial remaining"]')).toHaveAttribute('aria-valuenow', '42');
	await expect(navigation).toContainText('7,200 credits left');
	await toggle.click();
	await expect(ai).toBeVisible();
	await expect(navigation.getByRole('button', { name: /AI trial/ }), 'Trial rows do not open dialogs').toHaveCount(0);
	expect(await page.pageErrors()).toEqual([]);
});
