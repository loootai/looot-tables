import { test, expect } from '@playwright/test';
import { memberCookie } from './authenticated-test';

test('pasted keys are checked automatically, never block saving, and models live in Configuration → Defaults', async ({ page, context, baseURL }) => {
	await context.addCookies([{ name: 'looot-tables-session', value: memberCookie('browser-user'), url: baseURL!, httpOnly: true, sameSite: 'Lax' }]);
	await page.route('**/api/organization-settings', route => route.fulfill({ json: { local: true } }));
	await page.route('**/api/sheets', route => route.fulfill({ json: [] }));
	await page.route('**/api/looot/balance*', route => route.fulfill({ json: { credits: 1000, used: 0 } }));
	await page.route('**/api/openai/usage*', route => route.fulfill({ json: { enabled: false } }));
	const checks: Array<{ key: string; model: string; inference: boolean; only: string | null }> = [];
	await page.route('**/api/keys/verify*', async route => {
		if (route.request().method() === 'GET') return route.fulfill({ json: { openai: false, context: true, contextConnected: true, typesafe: false, passwordRequired: false } });
		const url = new URL(route.request().url()), headers = route.request().headers();
		const key = headers['x-openai-key'] ?? '';
		checks.push({ key, model: headers['x-openai-model'] ?? '', inference: url.searchParams.get('inference') === 'true', only: url.searchParams.get('only') });
		await route.fulfill({ json: { openai: key === 'sk-valid' ? { ok: true, inference: true } : { ok: false, issue: 'key', message: 'This key was rejected.' }, context: { ok: true }, typesafe: { configured: false, ok: false } } });
	});
	await page.goto('/app');
	const dialog = page.getByRole('dialog', { name: 'Set up enrichment' });
	await expect(dialog).toBeVisible();
	await expect(dialog.getByRole('combobox'), 'Model choice is not part of setup').toHaveCount(0);
	await expect(dialog.getByRole('region', { name: 'looot' })).toContainText('Connected');
	const proceed = dialog.getByRole('button', { name: 'Save and start', exact: true });
	await expect(proceed).toBeDisabled();
	const key = dialog.getByLabel('OpenAI API key', { exact: true });
	await key.fill('sk-invalid');
	await expect(dialog.getByText('This key was rejected.', { exact: true })).toBeVisible();
	await expect(proceed, 'A failed check never blocks saving').toBeEnabled();
	await key.fill('sk-valid');
	await expect(dialog.getByText('Connected', { exact: true })).toHaveCount(2);
	expect(checks.map(check => check.key)).toEqual(expect.arrayContaining(['sk-invalid', 'sk-valid']));
	expect(checks.every(check => check.inference && check.only === 'openai')).toBe(true);
	await proceed.click();
	await expect(dialog).toHaveCount(0);

	await page.goto('/app/settings');
	await expect(page.getByRole('dialog')).toHaveCount(0);
	const openaiRow = page.getByRole('region', { name: 'Connections' }).getByRole('listitem').filter({ hasText: 'OpenAI' });
	await expect(openaiRow).toContainText('Connected');
	expect(checks.at(-1), 'Opening Settings checks connections without a billed inference call').toMatchObject({ key: 'sk-valid', inference: false });
	await page.getByText('Advanced', { exact: true }).click();
	const models = page.getByRole('combobox', { name: 'AI model', exact: true });
	await expect(models).toHaveValue('gpt-6-luna');
	await expect(page.getByRole('combobox', { name: 'Yes/no and category answers', exact: true })).toBeVisible();
	const modelHelp = page.getByRole('button', { name: 'About AI model', exact: true });
	const tooltip = page.getByRole('tooltip');
	await modelHelp.hover();
	await expect(tooltip).toContainText('Any OpenAI model ID works.');
	await page.mouse.move(0, 0);
	await expect(tooltip).toHaveCount(0);
	await modelHelp.focus();
	await expect(tooltip).toBeVisible();
	await page.keyboard.press('Escape');
	await expect(tooltip).toHaveCount(0);
	await expect(modelHelp).toBeFocused();
	await page.setViewportSize({ width: 390, height: 740 });
	await modelHelp.hover();
	await expect(tooltip).toBeVisible();
	const tooltipBounds = await tooltip.boundingBox();
	expect(tooltipBounds!.x).toBeGreaterThanOrEqual(0);
	expect(tooltipBounds!.x + tooltipBounds!.width).toBeLessThanOrEqual(390);
	await page.mouse.move(0, 0);
	await page.setViewportSize({ width: 1360, height: 900 });
	await models.click();
	await models.fill('gpt-5.5');
	await page.getByRole('option', { name: 'gpt-5.5 OpenAI', exact: true }).click();
	await expect(page.getByText('This model works with your key.', { exact: true })).toBeVisible();
	expect(checks.at(-1)).toMatchObject({ model: 'gpt-5.5', inference: true, only: 'openai' });
	await page.getByRole('button', { name: 'Save defaults', exact: true }).click();
	await expect(page.getByRole('button', { name: 'Save defaults', exact: true })).toBeDisabled();
	await page.reload();
	await page.getByText('Advanced', { exact: true }).click();
	await expect(page.getByRole('combobox', { name: 'AI model', exact: true })).toHaveValue('gpt-5.5');
	expect(await page.pageErrors()).toEqual([]);
});
